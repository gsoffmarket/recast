import { mkdir, writeFile, access } from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';

/**
 * `recast new <dir>`: a starter project for someone else's app. It writes a config that uses the
 * generic HTTP fixture and oracle (no TypeScript), one example requirement wired to them, and a
 * short next-steps file. Everything it writes is validated by the same schemas `init` uses.
 */

export interface ScaffoldOptions {
  name?: string | undefined;
  legacyUrl: string;
  newUrl: string;
  apiUrl?: string | undefined;
  force: boolean;
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60) || 'my-app';

export function scaffoldFiles(dir: string, o: ScaffoldOptions): Record<string, string> {
  const name = slug(o.name ?? basename(resolve(dir)));
  const api = (o.apiUrl ?? o.legacyUrl).replace(/\/+$/, '');
  const hints = [
    `This is the ${name} web app.`,
    'If a login page appears, sign in as {{username}}.',
  ];
  const config = {
    name,
    environments: [
      { name: 'legacy', kind: 'source', baseUrl: o.legacyUrl, startPath: '/', hints },
      { name: 'new', kind: 'target', baseUrl: o.newUrl, startPath: '/', hints },
    ],
    fixture: {
      type: 'http',
      identity: 'fresh-item-v1',
      setup: {
        method: 'POST',
        url: `${api}/api/items`,
        body: { title: 'Recast check {{run}}' },
        capture: { item_id: 'id' },
      },
      cleanup: { method: 'DELETE', url: `${api}/api/items/{{item_id}}` },
    },
    oracle: {
      type: 'http',
      name: 'app-api',
      request: { method: 'GET', url: `${api}/api/items/{{item_id}}` },
      observe: { 'item.status': 'status' },
      until: { path: 'item.status', in: ['archived'] },
    },
    role: { username: 'recast-test' },
    kane: { maxSteps: 15, timeoutSec: 480 },
    budget: { minBalance: 150 },
  };
  const requirement = {
    id: 'REQ-ITEM-ARCHIVE',
    revision: 1,
    objective: 'A user can archive an item from its page in the web UI',
    role: 'web-ui-user',
    fixture: 'fresh-item-v1',
    inputs: {},
    action_intent: 'Open the page of the item with ID {{item_id}} and archive it using only the web UI.',
    oracle: 'app-api',
    settle_ms: 10000,
    assertions: [{ path: 'item.status', operator: 'equals', expected: 'archived' }],
    provenance: 'candidate',
    scope: ['items'],
    source_evidence: [],
  };
  const next = `# Next steps for ${name}

This folder was generated by \`recast new\`. It describes your app to Recast in JSON, so no code is needed.

## 1. Point it at your app

Open \`recast.config.json\`:

- **environments**: \`legacy\` is the UI you are replacing, \`new\` is the rewrite. Set \`baseUrl\` and \`startPath\` for each, and keep \`hints\` to navigation help only (never name the control a requirement is about).
- **fixture**: one API call that creates a fresh starting state for every run (here: create an item). \`capture\` keeps fields from the JSON response as variables, e.g. \`{ "item_id": "id" }\` or \`{ "order_id": "data.order.id" }\`. \`cleanup\` (optional) undoes it afterwards.
- **oracle**: one read-only API call that reports what really happened. \`observe\` maps response fields to observation names your requirements assert on. \`until\` polls until a final value appears.
- Put secrets in your shell or \`.env\` and reference them as \`{{env.NAME}}\`, e.g. \`"headers": { "authorization": "Bearer {{env.APP_TOKEN}}" }\`.
- No API to set up state? Use \`"fixture": { "type": "none", "identity": "shared-state-v1" }\` and assert on page readings: an action that ends "…and store it as status" is observed as \`ui.status\`.

## 2. Write requirements

Edit \`requirements/REQ-ITEM-ARCHIVE.json\` or copy it. \`fixture\` and \`oracle\` must match the names in the config. \`action_intent\` says what a user wants done, in words that fit both UIs, and can use captured variables such as \`{{item_id}}\`.

## 3. Run the loop

From the Recast repo, with Postgres, Redis and Kane CLI ready (see the main README):

\`\`\`bash
export RECAST_PROJECT=${name}
pnpm recast init --config ${join(dir, 'recast.config.json')}
pnpm recast doctor
pnpm recast requirements add ${join(dir, 'requirements', 'REQ-ITEM-ARCHIVE.json')}
pnpm recast baseline --requirement REQ-ITEM-ARCHIVE --runs 2
pnpm recast freeze   --requirement REQ-ITEM-ARCHIVE
pnpm recast compare  --requirement REQ-ITEM-ARCHIVE --target new --runs 2
pnpm recast report --format markdown
\`\`\`

To freeze the legacy app's behaviour without writing requirements, run \`pnpm recast discover run\`, then \`pnpm recast capture --dry-run\` to see the drafts and \`pnpm recast capture --yes\` to capture them. \`pnpm recast contract\` writes the result for whoever rebuilds the app, and \`pnpm recast check --target new\` tests a rebuild against every frozen requirement.

\`recast discover run\` maps the legacy UI with Kane Exploration and suggests more requirements. To let a coding agent repair gaps, add a \`repair\` section modelled on \`evaluation/trino/recast.config.json\`.
`;
  return {
    'recast.config.json': JSON.stringify(config, null, 2) + '\n',
    [join('requirements', 'REQ-ITEM-ARCHIVE.json')]: JSON.stringify(requirement, null, 2) + '\n',
    'NEXT_STEPS.md': next,
  };
}

export async function scaffoldProject(dir: string, o: ScaffoldOptions): Promise<string[]> {
  const files = scaffoldFiles(dir, o);
  if (!o.force) {
    for (const rel of Object.keys(files)) {
      const exists = await access(join(dir, rel)).then(() => true, () => false);
      if (exists) throw new Error(`${join(dir, rel)} already exists (use --force to overwrite)`);
    }
  }
  const written: string[] = [];
  for (const [rel, body] of Object.entries(files)) {
    const path = join(dir, rel);
    await mkdir(join(path, '..'), { recursive: true });
    await writeFile(path, body);
    written.push(path);
  }
  return written;
}
